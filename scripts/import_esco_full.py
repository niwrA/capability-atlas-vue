"""Import/reconcile the complete ESCO v1.2.1 catalogue from a local JSON-LD ZIP.

The archive is streamed, never extracted. SQLite checkpoints permit restart after
interruption; a SHA-256 digest binds the cache and inventory to the exact input.
No learning activities or prerequisite hypotheses are generated by this import.
"""
from __future__ import annotations

import argparse
from collections import Counter
from contextlib import closing
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sqlite3
from zipfile import ZipFile

from dataset_io import load_dataset, save_dataset
from esco_archive import iter_archive_graph

ROOT = Path(__file__).resolve().parents[1]
VERSION = '1.2.1'
CACHE_FORMAT = 1
LANGUAGES = ('en', 'nl')
RELATIONS = {
    'essential': ('relatedEssentialSkill', 'isEssentialSkillFor', 'esco_essential'),
    'optional': ('relatedOptionalSkill', 'isOptionalSkillFor', 'esco_optional'),
}


def as_list(value):
    return value if isinstance(value, list) else [] if value is None else [value]


def language_values(value):
    """Handle singleton/list SKOS-XL labels and ESCO NodeLiteral objects."""
    result = {language: [] for language in LANGUAGES}
    for item in as_list(value):
        if not isinstance(item, dict):
            continue
        for language, text in item.get('literalForm', {}).items():
            if language in result:
                result[language].extend(as_list(text))
        if item.get('language') in result and isinstance(item.get('nodeLiteral'), str):
            result[item['language']].append(item['nodeLiteral'])
    return {language: list(dict.fromkeys(text.strip() for text in texts if isinstance(text, str) and text.strip())) for language, texts in result.items()}


def normalize(record):
    types = as_list(record.get('type'))
    kind = 'occupation' if 'esco:Occupation' in types else 'skill' if 'esco:Skill' in types else 'classification'
    preferred = language_values(record.get('preferredLabel'))
    description = language_values(record.get('description'))
    definition = language_values(record.get('definition'))
    notes = language_values(record.get('scopeNote'))
    concept = {
        'id': record['uri'], 'kind': 'role' if kind == 'occupation' else kind,
        'label': next(iter(preferred['en']), None), 'label_nl': next(iter(preferred['nl']), None),
        'definition': next(iter(definition['en'] or description['en']), None),
        'definition_nl': next(iter(definition['nl'] or description['nl']), None),
        'source': 'ESCO', 'source_version': VERSION, 'official': True,
        'source_status': record.get('status'), 'source_types': types,
        'source_url': record['uri'], 'import_batch': 'ESCO full catalogue v1.2.1',
        'broader_ids': as_list(record.get('broader')),
        'in_scheme_ids': as_list(record.get('inScheme')),
        'alternative_labels': language_values(record.get('alternativeLabel')),
    }
    for key, field in [('notation', 'notation'), ('modified', 'source_modified'), ('issued', 'source_issued'),
                       ('identifier', 'source_identifiers'), ('hasNACECode', 'nace_codes'),
                       ('regulatedProfessionNote', 'regulated_profession'), ('replaces', 'replaces'),
                       ('isReplacedBy', 'replaced_by')]:
        if key in record:
            concept[field] = record[key]
    if any(notes.values()):
        concept['scope_notes'] = notes
    if any(definition.values()):
        concept['source_definitions'] = definition
    if kind == 'occupation':
        notation = str(record.get('notation', ''))
        concept['isco_major_group'] = notation[:1] or None
    if kind == 'skill':
        concept['esco_skill_type'] = str(record.get('skillType', '')).rsplit('/', 1)[-1] or None
        concept['skill_reuse_level'] = record.get('skillReuseLevel')
    concept['missing_source_fields'] = [field for field in ('label', 'label_nl', 'definition', 'definition_nl') if not concept[field]]
    direct = {relation: as_list(record.get(fields[0 if kind == 'occupation' else 1])) for relation, fields in RELATIONS.items()}
    associations = [
        {'from': association.get('isAssociationFor'), 'to': association.get('target'),
         'type': association.get('associationType'), 'id': association.get('uri')}
        for association in as_list(record.get('hasAssociation'))
    ]
    return {'kind': kind, 'status': record.get('status'), 'concept': concept, 'links': direct, 'associations': associations}


def digest_file(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def inventory_archive(archive):
    digest = digest_file(archive)
    directory = archive.parent / '.cache'
    directory.mkdir(parents=True, exist_ok=True)
    with closing(sqlite3.connect(directory / f'esco-{digest}-v{CACHE_FORMAT}.sqlite')) as connection:
        connection.execute('CREATE TABLE IF NOT EXISTS records (position INTEGER PRIMARY KEY, id TEXT UNIQUE, payload TEXT NOT NULL)')
        connection.execute('CREATE TABLE IF NOT EXISTS state (key TEXT PRIMARY KEY, value TEXT NOT NULL)')
        complete = connection.execute("SELECT value FROM state WHERE key='complete'").fetchone()
        if not complete:
            checkpoint = connection.execute('SELECT COALESCE(MAX(position), -1) FROM records').fetchone()[0]
            if checkpoint >= 0:
                print(f'Resuming archive inventory after graph record {checkpoint + 1}', flush=True)
            for position, record in enumerate(iter_archive_graph(archive)):
                if position <= checkpoint:
                    continue
                normalized = normalize(record)
                connection.execute('INSERT INTO records VALUES (?, ?, ?)', (position, record['uri'], json.dumps(normalized, ensure_ascii=False)))
                if (position + 1) % 1000 == 0:
                    connection.commit()
                    print(f'Inventoried {position + 1} source graph records', flush=True)
            connection.execute("INSERT OR REPLACE INTO state VALUES ('complete', 'true')")
            connection.commit()
        records = [json.loads(row[0]) for row in connection.execute('SELECT payload FROM records ORDER BY position')]
    return digest, records


def reconcile(records):
    occupations = {r['concept']['id']: r for r in records if r['kind'] == 'occupation' and r['status'] == 'released'}
    skills = {r['concept']['id']: r for r in records if r['kind'] == 'skill' and r['status'] == 'released'}
    for record in [*occupations.values(), *skills.values()]:
        if not record['concept']['label']:
            raise ValueError(f"Missing English preferred label for {record['concept']['id']}")
    direct, inverse, associations = set(), set(), set()
    unresolved = []
    for oid, record in occupations.items():
        for relation, ids in record['links'].items():
            for sid in ids:
                edge = (oid, sid, RELATIONS[relation][2])
                if sid not in skills:
                    unresolved.append(edge)
                else:
                    direct.add(edge)
        for association in record['associations']:
            relation = str(association['type']).rsplit('/', 1)[-1].replace('-skill', '')
            if relation in RELATIONS and association['from'] in occupations and association['to'] in skills:
                associations.add((association['from'], association['to'], RELATIONS[relation][2]))
    for sid, record in skills.items():
        for relation, ids in record['links'].items():
            for oid in ids:
                if oid in occupations:
                    inverse.add((oid, sid, RELATIONS[relation][2]))
    if unresolved:
        raise ValueError(f'{len(unresolved)} active occupation links target missing or obsolete skills: {unresolved[:3]}')
    if direct != inverse:
        raise ValueError(f'Forward/inverse relationships disagree: forward only {len(direct - inverse)}, inverse only {len(inverse - direct)}')
    return occupations, skills, direct, associations


def build_import(data, records, digest, archive_name):
    occupations, skills, expected_edges, associations = reconcile(records)
    all_source = {record['concept']['id']: record for record in records}
    previous_edges = {(edge['from'], edge['to'], edge['type']): edge for edge in data['role_capability_assertions'] if edge['type'].startswith('esco_')}
    new_occupations, new_skills, retained_obsolete = [], [], []
    for section, source in [('roles', occupations), ('capabilities', skills)]:
        existing = {concept['id']: concept for concept in data[section]}
        for concept in data[section]:
            if concept.get('source') != 'ESCO':
                continue
            original = all_source.get(concept['id'])
            if original is None or original['kind'] not in ('occupation', 'skill'):
                raise ValueError(f"Existing ESCO concept not present in archive: {concept['id']}")
            if original['status'] != 'released':
                retained_obsolete.append(concept['id'])
            # Keep Atlas annotations, but refresh official source fields.
            concept.update(original['concept'])
        additions = [source[id]['concept'] for id in sorted(source) if id not in existing]
        data[section].extend(additions)
        (new_occupations if section == 'roles' else new_skills).extend(concept['id'] for concept in additions)
    official_edges = {}
    for oid, sid, relation_type in sorted(expected_edges):
        key = (oid, sid, relation_type)
        official_edges[key] = {
            **previous_edges.get(key, {}),
            'from': oid, 'to': sid, 'type': relation_type,
            'validation': 'source_backed', 'source': 'ESCO v1.2.1 JSON-LD archive',
            'source_version': VERSION,
            'source_relationship': 'relatedEssentialSkill' if relation_type == 'esco_essential' else 'relatedOptionalSkill',
            'source_occupation_uri': oid, 'source_skill_uri': sid,
            'verified_against': 'esco_full_catalogue_import',
        }
    # Preserve order for previously represented links, then append new links.
    assertions, seen = [], set()
    for edge in data['role_capability_assertions']:
        key = (edge['from'], edge['to'], edge['type'])
        if not edge['type'].startswith('esco_'):
            assertions.append(edge)
        elif key in official_edges and key not in seen:
            assertions.append(official_edges[key])
            seen.add(key)
    assertions.extend(official_edges[key] for key in sorted(expected_edges - seen))
    data['role_capability_assertions'] = assertions
    data['esco_classifications'] = [record['concept'] for record in records if record['kind'] == 'classification']

    actual_occupations = {record['id'] for record in data['roles'] if record.get('source') == 'ESCO' and record.get('source_status') == 'released'}
    actual_skills = {record['id'] for record in data['capabilities'] if record.get('source') == 'ESCO' and record.get('source_status') == 'released'}
    actual_edges = {(e['from'], e['to'], e['type']) for e in assertions if e['type'].startswith('esco_')}
    if actual_occupations != set(occupations) or actual_skills != set(skills) or actual_edges != expected_edges:
        raise ValueError('Imported catalogue does not exactly match the source inventory')
    all_ids = [record['id'] for section in ('roles', 'capabilities', 'learning_units', 'framework_outcomes', 'qualifications') for record in data.get(section, [])]
    if len(all_ids) != len(set(all_ids)):
        raise ValueError('Duplicate node IDs after import')
    node_ids = set(all_ids)
    for section in ('role_capability_assertions', 'decompositions', 'outcome_capability_links', 'qualification_requirements'):
        for edge in data.get(section, []):
            if edge['from'] not in node_ids or edge['to'] not in node_ids:
                raise ValueError(f'Dangling reference in {section}: {edge}')
    linked_skills = {edge[1] for edge in expected_edges}
    fingerprints = {
        'occupation_ids': hash_lines(sorted(occupations)),
        'skill_ids': hash_lines(sorted(skills)),
        'occupation_skill_links': hash_lines(['\t'.join(edge) for edge in sorted(expected_edges)]),
    }
    report = {
        'source': {'version': VERSION, 'archive': archive_name, 'sha256': digest,
                   'languages': list(LANGUAGES), 'active_status': 'released'},
        'inventory': {
            'occupations': len(occupations), 'skill_knowledge_concepts': len(skills),
            'occupation_skill_links': len(expected_edges),
            'essential_links': sum(edge[2] == 'esco_essential' for edge in expected_edges),
            'optional_links': sum(edge[2] == 'esco_optional' for edge in expected_edges),
            'occupation_linked_skills': len(linked_skills), 'skills_without_occupation_links': len(set(skills) - linked_skills),
            'excluded_obsolete_occupations': sum(r['kind'] == 'occupation' and r['status'] == 'obsolete' for r in records),
            'excluded_obsolete_skills': sum(r['kind'] == 'skill' and r['status'] == 'obsolete' for r in records),
            'classification_and_support_records': len(data['esco_classifications']),
        },
        'fingerprints_sha256': fingerprints,
        'reconciliation': {'missing_occupations': [], 'missing_skills': [], 'missing_links': [], 'unexpected_active_concepts': [], 'dangling_graph_references': []},
        'source_relationship_policy': {
            'primary': 'relatedEssentialSkill/relatedOptionalSkill on released occupations',
            'cross_check': 'Exact equality with isEssentialSkillFor/isOptionalSkillFor on released skills',
            'embedded_association_object_links': len(associations),
            'primary_only_links': len(expected_edges - associations),
            'embedded_only_links': len(associations - expected_edges),
            'note': 'Embedded AssociationObject lists differ from the mutually consistent forward/inverse properties; they are not used to override those properties.',
        },
        'missing_source_fields': dict(Counter(field for record in [*occupations.values(), *skills.values()] for field in record['concept']['missing_source_fields'])),
        'concepts_with_missing_source_fields': [{'id': record['concept']['id'], 'fields': record['concept']['missing_source_fields']} for record in [*occupations.values(), *skills.values()] if record['concept']['missing_source_fields']],
        'retained_obsolete_concepts': sorted(retained_obsolete),
        'obsolete_source_inventory': [
            {'id': r['concept']['id'], 'kind': r['kind'], 'replaced_by': r['concept'].get('replaced_by')}
            for r in records if r['kind'] in ('occupation', 'skill') and r['status'] == 'obsolete'
        ],
        'changes': {'occupations_added': len(new_occupations), 'skills_added': len(new_skills),
                    'links_added': len(expected_edges - set(previous_edges)),
                    'prior_links_not_in_active_source': [list(edge) for edge in sorted(set(previous_edges) - expected_edges)]},
        'completed_at_utc': datetime.now(timezone.utc).isoformat(),
    }
    previous_report = data.get('esco_full_catalogue_import')
    if previous_report and previous_report['source']['sha256'] == digest and previous_report['fingerprints_sha256'] == fingerprints:
        report['changes'] = previous_report['changes']
        report['completed_at_utc'] = previous_report['completed_at_utc']
    data['esco_full_catalogue_import'] = report
    data['metadata']['title'] = 'Complete ESCO v1.2.1 catalogue with Atlas draft learning pathways'
    if 'historical_sample_note' not in data['metadata']:
        data['metadata']['historical_sample_note'] = data['metadata'].get('note')
    data['metadata']['source'] = 'User-supplied ESCO v1.2.1 JSON-LD classification archive, all released occupations and skill/knowledge concepts; English and Dutch source text, plus existing Atlas-authored learning content and roles.'
    data['metadata']['note'] = f'The active ESCO catalogue is reconciled exactly against the archive inventory and its mutually consistent forward/inverse occupation-skill properties. Catalogue coverage is complete for that release; Atlas learning activities and prerequisite links remain incomplete, proposed, and unvalidated. {len(retained_obsolete)} previously represented obsolete concepts are retained for learner-state compatibility. Earlier sample methodology is recorded in historical_sample_note and esco_v025_import.'
    data['metadata']['catalogue_scope'] = 'All released ESCO v1.2.1 occupations and skill/knowledge concepts from the supplied archive; existing obsolete concepts are retained only for learner-state compatibility.'
    data['metadata']['catalogue_import_report'] = 'esco_full_catalogue_import'
    return data, report


def hash_lines(lines):
    return hashlib.sha256(('\n'.join(lines) + '\n').encode('utf-8')).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--inventory-only', action='store_true')
    args = parser.parse_args()
    candidates = sorted((ROOT / 'input').glob('*.zip'))
    archive = args.archive or (candidates[0] if len(candidates) == 1 else None)
    if archive is None:
        parser.error('Specify --archive when input/ does not contain exactly one ZIP')
    if 'v1.2.1' not in archive.name:
        parser.error('This importer is explicitly scoped to the ESCO v1.2.1 archive')
    digest, records = inventory_archive(archive)
    occupations, skills, direct, associations = reconcile(records)
    print(json.dumps({
        'archive_sha256': digest, 'source_records': len(records),
        'occupations': len(occupations), 'skills': len(skills),
        'relationships': len(direct), 'association_object_relationships': len(associations),
        'direct_only': len(direct - associations), 'association_only': len(associations - direct),
        'statuses': dict(Counter(f"{r['kind']}:{r['status']}" for r in records)),
    }, indent=2), flush=True)
    if not args.inventory_only:
        data, report = build_import(load_dataset(), records, digest, archive.name)
        with ZipFile(archive) as zipped:
            members = [entry for entry in zipped.infolist() if entry.filename.endswith(('.json-ld', '.jsonld'))]
            if len(members) != 1 or 'v1.2.1' not in members[0].filename:
                raise ValueError('The JSON-LD member does not identify ESCO v1.2.1')
            report['source']['member'] = members[0].filename
            report['source']['uncompressed_bytes'] = members[0].file_size
        save_dataset(data)
        print('Published complete source manifest after exact reconciliation. No learning activities were generated.', flush=True)
        print(json.dumps(report['changes'], indent=2), flush=True)


if __name__ == '__main__':
    main()
